"""Generate the high-level Pythonic layer from ``webgpu.json`` + the compiled lib.

The spec (``webgpu.json``) provides *structure* (which enums/flags/structs/
objects exist, their members, types, defaults and docstrings); the compiled
extension provides *values* (enum integers) and *validation* (every C name we
derive must actually resolve). Anything that does not resolve raises, so a
submodule bump can never silently emit wrong bindings.

Generates, into ``wgpu/_generated/``:

* ``enums.py``     -- one ``IntEnum`` per spec enum, plus ``BY_SPEC_NAME``
* ``flags.py``     -- one ``IntFlag`` per spec bitflag, plus ``BY_SPEC_NAME``
* ``structs.py``   -- declarative descriptors driving the runtime struct builder
* ``constants.py`` -- the WebGPU sentinel constants
* ``objects.py``   -- the object/method table (C functions, args, lifecycles)
* ``classes.py``   -- the ``GPU*`` wrapper classes

The output is committed, so bumping the submodule yields a reviewable diff, and
it never imports this package: the runtime must work in a wheel that ships no
generator.
"""

from __future__ import annotations

import json
import keyword
from pathlib import Path

from . import bridge as from_bridge
from . import naming, paths

GENERATED_DIR = paths.REPO_ROOT / "wgpu" / "_generated"

_BANNER = """\
# AUTO-GENERATED by `python -m bindgen.generate`. DO NOT EDIT.
#
# Source of truth: wgpu-native/ffi/webgpu-headers/webgpu.json (the machine-
# readable WebGPU spec) plus the compiled extension for enum values. Re-run the
# generator after bumping the wgpu-native submodule.
"""


def load_spec() -> dict:
    return json.loads(paths.WEBGPU_JSON.read_text())


def _import_module():
    """Load the compiled low-level extension (exposes ``.lib`` and ``.ffi``)."""
    from .ffi_build import NATIVE_DIR, load_compiled

    return load_compiled(NATIVE_DIR)


def _docstring(text: str | None, indent: str) -> str:
    text = (text or "").strip()
    if not text or text == "TODO":
        return ""
    # Escape so arbitrary upstream doc text can never produce invalid Python
    # (a stray triple quote or a trailing backslash would otherwise break it).
    text = text.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    lines = text.splitlines()
    if len(lines) == 1 and not lines[0].endswith('"'):
        return f'{indent}"""{lines[0]}"""\n'
    body = "\n".join(indent + ln if ln else "" for ln in lines)
    return f'{indent}"""\n{body}\n{indent}"""\n'


def _member_ident(spec_name: str) -> str:
    ident = naming.py_enum_member(spec_name)
    if keyword.iskeyword(ident):
        ident += "_"
    return ident


def _emit_enum_like(spec_group, lib, base_class, c_value_fn) -> str:
    """Shared emitter for enums and bitflags."""
    out: list[str] = []
    for item in spec_group:
        py_name = naming.py_enum_name(item["name"])
        out.append(f"class {py_name}({base_class}):")
        doc = _docstring(item.get("doc"), "    ")
        if doc:
            out.append(doc.rstrip("\n"))
        seen: set[str] = set()
        emitted = 0
        for entry in item["entries"]:
            if entry is None:
                continue
            c_name = c_value_fn(item["name"], entry["name"])
            value = int(getattr(lib, c_name))  # validates + reads real value
            ident = _member_ident(entry["name"])
            if ident in seen:
                continue
            seen.add(ident)
            out.append(f"    {ident} = {value}")
            emitted += 1
        if emitted == 0:
            out.append("    pass")
        out.append("")
        out.append("")
    return "\n".join(out)


def _by_spec_name(spec_group) -> str:
    """Emit a spec-name -> class map, so the runtime never needs the generator."""
    lines = ["BY_SPEC_NAME = {"]
    for item in spec_group:
        lines.append(f"    {item['name']!r}: {naming.py_enum_name(item['name'])},")
    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def generate_enums(spec, lib) -> str:
    body = _emit_enum_like(spec["enums"], lib, "enum.IntEnum", naming.c_enum_value)
    return f"{_BANNER}\nimport enum\n\n\n{body}{_by_spec_name(spec['enums'])}"


def generate_flags(spec, lib) -> str:
    body = _emit_enum_like(spec["bitflags"], lib, "enum.IntFlag", naming.c_enum_value)
    return f"{_BANNER}\nimport enum\n\n\n{body}{_by_spec_name(spec['bitflags'])}"


# ---- structs ---------------------------------------------------------------


def _parse_member_type(spec_type: str) -> tuple[str, str | None, bool]:
    """Return ``(kind, ref, is_array)`` for a spec member ``type`` string.

    ``kind`` is one of: prim, string, out_string, enum, bitflag, struct,
    object, callback, c_void. ``ref`` is the referenced spec name for
    enum/bitflag/struct/object/callback, else ``None``.
    """
    is_array = spec_type.startswith("array<")
    if is_array:
        spec_type = spec_type[len("array<") : -1]
    if "." in spec_type:
        cat, ref = spec_type.split(".", 1)
        kind = {
            "enum": "enum",
            "bitflag": "bitflag",
            "struct": "struct",
            "object": "object",
            "callback": "callback",
        }.get(cat, cat)
        return kind, ref, is_array
    if spec_type in ("string_with_default_empty", "nullable_string"):
        return "string", None, is_array
    if spec_type == "out_string":
        return "out_string", None, is_array
    if spec_type == "c_void":
        return "c_void", None, is_array
    return "prim", spec_type, is_array


def _resolve_default(mem, kind, ref, lib, idl_default=None):
    """Resolve a spec default to something the runtime can use directly.

    Enum/bitflag member names become plain integers here, so the runtime never
    has to map spec names back to Python identifiers. ``constant.*`` defaults
    stay symbolic because some are size_t-width and must be resolved per target.
    """
    default = mem.get("default")
    if default is None and idl_default is not None:
        # The IDL spells enum defaults as quoted web strings ("uniform"); the
        # C-side value is looked up through the same table the runtime uses.
        value = idl_default.strip()
        if value == "{}":
            # The IDL marks a nested struct that must be built even when
            # omitted, so its own defaults apply -- multisample state defaults
            # to {} and thus to count 1, while a binding layout's sampler has
            # no default and must stay unset.
            return {} if kind == "struct" else None
        if value == "[]":
            # An empty sequence -- ``requiredFeatures = []`` and friends. The C
            # side spells that as a zero count and a null pointer, which is what
            # the struct already holds, so there is nothing to write. Returning
            # the ref's enum value here instead would be nonsense: the default
            # describes the *list*, not one element of it.
            return None
        value = value.strip('"')
        if kind == "enum":
            from wgpu._generated import apienums

            table = apienums.TO_INT.get(ref)
            return None if table is None else table[value]
        if value in ("True", "False"):
            return value == "True"
        try:
            return int(value)
        except ValueError:
            return None
    if not isinstance(default, str):
        return default
    if default.startswith("constant.") or default.startswith("0x"):
        return default
    if kind in ("enum", "bitflag"):
        return int(getattr(lib, naming.c_enum_value(ref, default)))
    return default


def generate_structs(spec, ffi, lib, bridge=None) -> str:
    """Emit declarative descriptors for every struct, validated against the ffi.

    Each descriptor records the C type/field names, member kinds, pointer-ness,
    optionality and defaults -- everything a runtime builder needs to turn a
    Python mapping into a filled cffi struct. Every C field name is checked to
    exist on the real compiled type, so a naming drift fails generation.

    When a ``bridge`` is given, each member's public keyword takes its name from
    the Web IDL instead of from the C field, so the builder consumes mappings
    written in the public API's vocabulary directly -- no translation layer, and
    no per-call renaming at runtime.
    """

    # All three maps below are read back with the *C header* field name, the way
    # the member loop spells it. ``bridge.struct_fields`` answers in webgpu.json's
    # spelling instead (``sample_type``, not ``sampleType``), so it is converted
    # once here. Keying them differently on the two sides silently loses every
    # multi-word member -- and only those, which is why a binding layout's
    # ``type`` kept its default while its ``sample_type`` quietly lost one.
    def _c_key(spec_member: str) -> str:
        return naming.c_struct_field(spec_member)

    # C struct name -> {C member -> public keyword}, from the IDL.
    public_names: dict[str, dict[str, str]] = {}
    adapters: dict[str, list[tuple[str, str]]] = {}
    # The Web IDL carries defaults the C spec leaves unset -- a buffer binding
    # layout's type is "uniform" there, and merely absent in webgpu.json. The
    # public API's defaults are the IDL's, so they win where the C spec is silent.
    idl_defaults: dict[str, dict[str, str]] = {}
    # Members the IDL marks ``required``. The C spec has no such notion -- every
    # field of a C struct exists, zeroed -- so without this an omitted width
    # reaches wgpu-native as a zero-sized texture rather than as an error.
    idl_required: dict[str, set[str]] = {}
    if bridge is not None:
        for idl_struct, fields in bridge.idl.structs.items():
            spec_struct = bridge.structs.get(idl_struct)
            if spec_struct is None:
                continue
            for fname, attr in fields.items():
                c_member = bridge.struct_fields.get((idl_struct, fname))
                if c_member is None:
                    continue
                if attr.default is not None:
                    idl_defaults.setdefault(spec_struct, {})[_c_key(c_member)] = (
                        attr.default
                    )
                if attr.required:
                    idl_required.setdefault(spec_struct, set()).add(_c_key(c_member))
    if bridge is not None:
        for (idl_struct, idl_field), c_member in bridge.struct_fields.items():
            spec_struct = bridge.structs[idl_struct]
            public = from_bridge.camel_to_snake(idl_field)
            public_names.setdefault(spec_struct, {})[_c_key(c_member)] = public
        for (idl_struct, idl_field), (adapter, target) in bridge.shape_adapted.items():
            spec_struct = bridge.structs.get(idl_struct)
            if spec_struct is None:
                continue  # a field of a web-only struct
            public = from_bridge.camel_to_snake(idl_field)
            adapters.setdefault(spec_struct, []).append((public, adapter, target))
    lines = [
        _BANNER,
        '"""Declarative descriptors for every wgpu-native struct.',
        "",
        "``STRUCTS[spec_name]`` maps to a ``StructDescriptor``. The runtime struct",
        "builder consumes these; they are generated, not hand-written.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from dataclasses import dataclass, field",
        "",
        "",
        "@dataclass(frozen=True)",
        "class Member:",
        "    py: str          # pythonic keyword name",
        "    c: str           # C struct field name",
        "    kind: str        # prim|string|out_string|enum|bitflag|struct|object|callback|c_void",
        "    ref: str | None  # referenced spec name (enum/bitflag/struct/object)",
        "    pointer: str | None",
        "    optional: bool",
        "    default: object",
        "    array: bool",
        "    count_c: str | None  # C count field, for arrays",
        "    # Marked ``required`` in the Web IDL. The C spec has no such notion --",
        "    # every field of a C struct exists, zeroed -- so this is the only",
        "    # thing standing between an omitted width and a zero-sized texture.",
        "    required: bool = False",
        "",
        "",
        "@dataclass(frozen=True)",
        "class StructDescriptor:",
        "    c_name: str",
        "    category: str    # extensible|standalone|extension|extensible_callback_arg",
        "    members: tuple = field(default_factory=tuple)",
        "    # (public field, adapter, target) for fields whose *shape* differs",
        "    # between the Web and C specs; see wgpu._api.adapt. The target is",
        "    # the extension struct to chain or the member to nest under.",
        "    adapters: tuple = field(default_factory=tuple)",
        "    # The WGPUSType tag, for structs that chain onto another.",
        "    s_type: int = 0",
        "",
        "",
        "STRUCTS: dict[str, StructDescriptor] = {}",
        "",
    ]

    for st in spec["structs"]:
        c_name = naming.c_type_name(st["name"])
        c_type = ffi.typeof(c_name)  # validates the struct type exists
        c_fields = {f[0] for f in (c_type.fields or [])}

        members_src = []
        for mem in st.get("members", []):
            kind, ref, is_array = _parse_member_type(mem["type"])
            c_field = naming.c_struct_field(mem["name"])
            assert c_field in c_fields, f"{c_name} has no field {c_field}"
            count_c = None
            if is_array:
                count_c = naming.c_array_count_field(mem["name"])
                assert count_c in c_fields, f"{c_name} has no count field {count_c}"
            members_src.append(
                "        Member(py={!r}, c={!r}, kind={!r}, ref={!r}, pointer={!r}, "
                "optional={!r}, default={!r}, array={!r}, count_c={!r}, "
                "required={!r}),".format(
                    public_names.get(st["name"], {}).get(
                        c_field, naming.py_member_name(mem["name"])
                    ),
                    c_field,
                    kind,
                    ref,
                    mem.get("pointer"),
                    bool(mem.get("optional", False)),
                    _resolve_default(
                        mem,
                        kind,
                        ref,
                        lib,
                        idl_defaults.get(st["name"], {}).get(c_field),
                    ),
                    is_array,
                    count_c,
                    c_field in idl_required.get(st["name"], ()),
                )
            )
        s_type = 0
        if st.get("type") == "extension":
            # Chained structs carry a tag so C knows what they are.
            s_type = int(getattr(lib, naming.c_enum_value("s_type", st["name"])))
        lines.append(f"STRUCTS[{st['name']!r}] = StructDescriptor(")
        lines.append(f"    c_name={c_name!r},")
        lines.append(f"    category={st.get('type')!r},")
        if adapters.get(st["name"]):
            lines.append(f"    adapters={tuple(sorted(adapters[st['name']]))!r},")
        if s_type:
            lines.append(f"    s_type={s_type},")
        if members_src:
            lines.append("    members=(")
            lines.extend(members_src)
            lines.append("    ),")
        lines.append(")")
        lines.append("")
    return "\n".join(lines)


# ---- constants -------------------------------------------------------------

# Symbolic constant values in the spec, mapped to a cross-platform-correct
# Python expression. size_t-width values are resolved at runtime from the ffi so
# the committed file stays correct on 32- and 64-bit targets alike.
_CONST_EXPR = {
    "uint32_max": "0xFFFFFFFF",
    "uint64_max": "0xFFFFFFFFFFFFFFFF",
    "usize_max": "_SIZE_T_MAX",
    "nan": 'float("nan")',
}


def generate_constants(spec) -> str:
    lines = [
        _BANNER,
        '"""WebGPU sentinel constants (e.g. WHOLE_SIZE), from webgpu.json."""',
        "",
        "from wgpu._native import ffi as _ffi",
        "",
        "_SIZE_T_MAX = (1 << (8 * _ffi.sizeof('size_t'))) - 1",
        "",
    ]
    for const in spec["constants"]:
        expr = _CONST_EXPR[const["value"]]
        lines.append(f"{const['name']} = {expr}")
    lines.append("")
    lines.append("#: The wgpu-native release this package was generated against.")
    lines.append(f"WGPU_NATIVE_VERSION = {paths.native_version()!r}")
    lines.append("")
    lines.append("#: The exact wgpu-native commit compiled into this package.")
    lines.append("#: Statically linked, so there is no library file to ask later.")
    lines.append(f"WGPU_NATIVE_COMMIT_SHA = {paths.native_commit_sha()!r}")
    lines.append("")
    return "\n".join(lines)


# ---- objects & methods -----------------------------------------------------


def _arg_descriptor(arg: dict) -> str:
    """Emit an ``Arg(...)`` literal for a method argument."""
    kind, ref, is_array = _parse_member_type(arg["type"])
    count_c = naming.c_array_count_field(arg["name"]) if is_array else None
    return (
        "Arg(py={!r}, kind={!r}, ref={!r}, pointer={!r}, optional={!r}, "
        "array={!r}, count_c={!r})".format(
            naming.py_member_name(arg["name"]),
            kind,
            ref,
            arg.get("pointer"),
            bool(arg.get("optional", False)),
            is_array,
            count_c,
        )
    )


def _c_arg_count(lib, ffi, c_func: str) -> int:
    return len(ffi.typeof(getattr(lib, c_func)).args)


def generate_objects(spec, lib, ffi) -> str:
    """Emit the declarative method table for every object, validated against
    the compiled lib (each C function exists and its arg count matches)."""
    lines = [
        _BANNER,
        '"""Declarative object/method descriptors, generated from webgpu.json.',
        "",
        "The runtime invoker turns these into live Python method calls. Names and",
        "arg counts are validated against the compiled extension at generation.",
        '"""',
        "",
        "from __future__ import annotations",
        "",
        "from dataclasses import dataclass, field",
        "",
        "",
        "@dataclass(frozen=True)",
        "class Arg:",
        "    py: str",
        "    kind: str        # prim|string|enum|bitflag|struct|object|c_void",
        "    ref: str | None",
        "    pointer: str | None",
        "    optional: bool",
        "    array: bool",
        "    count_c: str | None",
        "",
        "",
        "@dataclass(frozen=True)",
        "class Method:",
        "    py: str",
        "    c_func: str",
        "    args: tuple = ()",
        "    ret_kind: str | None = None   # None == void",
        "    ret_ref: str | None = None",
        "    ret_optional: bool = False",
        "    is_async: bool = False",
        "    callback_ref: str | None = None",
        "    callback_info_c: str | None = None  # e.g. WGPURequestAdapterCallbackInfo",
        "    callback_result_ref: str | None = None  # object the callback returns",
        "    doc: str = ''",
        "",
        "",
        "@dataclass(frozen=True)",
        "class ObjectType:",
        "    c_name: str",
        "    release_func: str = ''   # e.g. wgpuDeviceRelease",
        "    add_ref_func: str = ''   # e.g. wgpuDeviceAddRef",
        "    methods: tuple = field(default_factory=tuple)",
        "",
        "",
        "OBJECTS: dict[str, ObjectType] = {}",
        "",
    ]

    callbacks = {cb["name"]: cb for cb in spec["callbacks"]}

    def _callback_result(callback_ref):
        cb = callbacks[callback_ref.split(".", 1)[1]]
        for a in cb.get("args", []):
            if a["type"].startswith("object."):
                return a["type"].split(".", 1)[1]
        return None

    for obj in spec["objects"]:
        c_name = naming.c_type_name(obj["name"])
        methods_src = []
        for meth in obj.get("methods", []):
            c_func = naming.c_method_func(obj["name"], meth["name"])
            n_c_args = _c_arg_count(lib, ffi, c_func)  # validates func exists
            is_async = "callback" in meth
            args = meth.get("args", [])
            # expected C args: self + (2 per array arg else 1) + (1 if async)
            expected = 1 + sum(2 if a["type"].startswith("array<") else 1 for a in args)
            expected += 1 if is_async else 0
            assert expected == n_c_args, (
                f"{c_func}: arg-count mismatch spec={expected} c={n_c_args}"
            )
            ret = meth.get("returns")
            ret_kind = ret_ref = None
            ret_optional = False
            if ret and not is_async:
                ret_kind, ret_ref, _ = _parse_member_type(ret["type"])
                ret_optional = bool(ret.get("optional", False))
            callback_info_c = None
            callback_result_ref = None
            if is_async:
                cb = meth["callback"].split(".", 1)[1]
                callback_info_c = naming.c_type_name(cb) + "CallbackInfo"
                callback_result_ref = _callback_result(meth["callback"])
            args_src = ",\n            ".join(_arg_descriptor(a) for a in args)
            methods_src.append(
                "        Method(\n"
                f"            py={meth['name']!r}, c_func={c_func!r},\n"
                f"            args=({args_src}{',' if args else ''}),\n"
                f"            ret_kind={ret_kind!r}, ret_ref={ret_ref!r}, ret_optional={ret_optional!r},\n"
                f"            is_async={is_async!r}, callback_ref={meth.get('callback')!r},\n"
                f"            callback_info_c={callback_info_c!r},\n"
                f"            callback_result_ref={callback_result_ref!r},\n"
                f"            doc={_clean_doc(meth.get('doc'))!r},\n"
                "        ),"
            )
        release_func = naming.c_object_lifecycle(obj["name"], "Release")
        add_ref_func = naming.c_object_lifecycle(obj["name"], "AddRef")
        for fn in (release_func, add_ref_func):
            getattr(lib, fn)  # validate the lifecycle functions exist
        lines.append(f"OBJECTS[{obj['name']!r}] = ObjectType(")
        lines.append(f"    c_name={c_name!r},")
        lines.append(f"    release_func={release_func!r},")
        lines.append(f"    add_ref_func={add_ref_func!r},")
        if methods_src:
            lines.append("    methods=(")
            lines.extend(methods_src)
            lines.append("    ),")
        lines.append(")")
        lines.append("")
    return "\n".join(lines)


def _clean_doc(text: str | None) -> str:
    text = (text or "").strip()
    return "" if text in ("", "TODO") else text


