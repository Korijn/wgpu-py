def generate_classes(spec, bridge=None) -> str:
    """Emit ``GPU*`` classes for wgpu-native objects the Web IDL does not model.

    Most objects get their public class from ``apiclasses.py``, generated from
    the IDL. A few exist only in the C API -- the instance, and the surface that
    backs presentation -- so their classes are derived from the C spec instead.
    Signatures come straight from webgpu.json; bodies dispatch like any other.
    """
    import keyword as _kw

    covered = set(bridge.classes.values()) if bridge else set()
    unimplemented = paths.unimplemented_functions()
    lines = [
        _BANNER,
        '"""``GPU*`` classes for wgpu-native objects with no Web IDL counterpart."""',
        "",
        "from wgpu._api.base import GPUHandle",
        "",
    ]
    for obj in spec["objects"]:
        if obj["name"] in covered:
            continue
        if naming.c_object_lifecycle(obj["name"], "Release") in unimplemented:
            # Nothing Python can own: every handle it holds has to be released
            # eventually, and calling an unimplemented function aborts the
            # process. External textures are the case today -- they can only be
            # made from a browser image source, so wgpu-native never implemented
            # their lifetime -- and a class nobody can hold an instance of is
            # worse than no class, because it shows up in the object counts.
            continue
        cls = "GPU" + naming.py_class_name(obj["name"])
        lines.append(f"class {cls}(GPUHandle):")
        lines.append(f"    _spec_name = {obj['name']!r}")
        lines.append("")
        methods = obj.get("methods", [])
        if not methods:
            lines.append("    pass")
            lines.append("")
        for meth in methods:
            args = meth.get("args", [])
            # A default (=None) is only valid for a trailing run of optional args,
            # since Python forbids a defaulted param before a required one. The
            # invoker still accepts None for any optional arg.
            can_default = [False] * len(args)
            for i in range(len(args) - 1, -1, -1):
                if args[i].get("optional") and (
                    i == len(args) - 1 or can_default[i + 1]
                ):
                    can_default[i] = True
                else:
                    break
            params = ["self"]
            names = []
            for i, arg in enumerate(args):
                name = naming.py_member_name(arg["name"])
                if _kw.iskeyword(name):
                    name += "_"
                names.append(name)
                params.append(f"{name}=None" if can_default[i] else name)
            call_args = ", ".join(names)
            sig = ", ".join(params)
            lines.append(f"    def {_py_method(meth['name'])}({sig}):")
            doc = _docstring(meth.get("doc"), "        ")
            if doc:
                lines.append(doc.rstrip("\n"))
            passthrough = f", {call_args}" if call_args else ""
            lines.append(f"        return self._call({meth['name']!r}{passthrough})")
            lines.append("")
        lines.append("")
    return "\n".join(lines)


def _py_method(name: str) -> str:
    import keyword as _kw

    return name + "_" if _kw.iskeyword(name) else name


def write_all(out_dir: Path = GENERATED_DIR) -> list[Path]:
    from . import genapi

    spec = load_spec()
    bridge = from_bridge.build()
    mod = _import_module()
    lib, ffi = mod.lib, mod.ffi
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "__init__.py").write_text(
        _BANNER + '\n"""Auto-generated Pythonic layer for wgpu-native."""\n'
    )
    written = []
    for fname, text in [
        ("enums.py", generate_enums(spec, lib)),
        ("flags.py", generate_flags(spec, lib)),
        ("structs.py", generate_structs(spec, ffi, lib, bridge)),
        ("constants.py", generate_constants(spec)),
        ("objects.py", generate_objects(spec, lib, ffi)),
        ("classes.py", generate_classes(spec, bridge)),
        ("apienums.py", genapi.generate_api_enums(bridge, lib)),
        ("apiflags.py", genapi.generate_api_flags(bridge)),
        ("apistructs.py", genapi.generate_api_structs(bridge)),
        ("apiclasses.py", genapi.generate_api_classes(bridge, spec, mod)),
    ]:
        path = out_dir / fname
        path.write_text(text)
        written.append(path)
    return written


if __name__ == "__main__":
    for p in write_all():
        print("wrote", p.relative_to(paths.REPO_ROOT))
